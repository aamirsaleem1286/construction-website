import sharp from "sharp";
import { readdir, writeFile, stat, rename } from "node:fs/promises";
import path from "node:path";

const dir = "public/images";
const files = (await readdir(dir)).filter((f) => f.endsWith(".jpg") && f !== "contact-sheet.jpg");
const blur = {};

for (const file of files) {
  const full = path.join(dir, file);
  const before = (await stat(full)).size;
  const tmp = path.join(dir, `tmp-${file}`);
  const pipeline = sharp(full).rotate().resize({
    width: 2000,
    height: 2000,
    fit: "inside",
    withoutEnlargement: true,
  });
  await pipeline.jpeg({ quality: 78, progressive: true, mozjpeg: true }).toFile(tmp);
  await rename(tmp, full);
  const after = (await stat(full)).size;
  const small = await sharp(full).resize(24, 24, { fit: "cover" }).jpeg({ quality: 40 }).toBuffer();
  blur[`/images/${file}`] = `data:image/jpeg;base64,${small.toString("base64")}`;
  console.log(`${file}: ${(before / 1024).toFixed(0)}kB -> ${(after / 1024).toFixed(0)}kB`);
}

const lines = Object.entries(blur)
  .map(([k, v]) => `  "${k}": "${v}",`)
  .join("\n");

await writeFile(
  "lib/image-blur.ts",
  `// Auto-generated by scripts/optimize-images.mjs — tiny base64 placeholders for next/image.\nconst blurData: Record<string, string> = {\n${lines}\n};\n\nexport function getBlurDataURL(src: string): string | undefined {\n  return blurData[src];\n}\n`,
  "utf8"
);
console.log(`\nWrote blur map for ${Object.keys(blur).length} images`);
