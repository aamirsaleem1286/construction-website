import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
const dir = "public/images";
const files = (await readdir(dir)).filter((f) => f.endsWith(".jpg"));
const blur = {};
for (const file of files) {
  try {
    const full = path.join(dir, file);
    const small = await sharp(full).resize(24, 24, { fit: "cover" }).jpeg({ quality: 40 }).toBuffer();
    blur[`/images/${file}`] = `data:image/jpeg;base64,${small.toString("base64")}`;
  } catch (e) {
    console.log("skip", file, e.message);
  }
}
const lines = Object.entries(blur).map(([k, v]) => `  "${k}": "${v}",`).join("\n");
await writeFile("lib/image-blur.ts", `// Auto-generated by scripts/optimize-images.mjs — tiny base64 placeholders for next/image.\nconst blurData: Record<string, string> = {\n${lines}\n};\n\nexport function getBlurDataURL(src: string): string | undefined {\n  return blurData[src];\n}\n`, "utf8");
console.log(`Wrote blur map for ${Object.keys(blur).length} images`);
